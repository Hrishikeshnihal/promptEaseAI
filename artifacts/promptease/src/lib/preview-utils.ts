import React from "react";

/**
 * Standardizes and cleans generated code before it's injected into the preview iframe.
 * 1. Removes markdown fences.
 * 2. Normalizes component names to 'App'.
 * 3. Ensures a default export exists.
 */
export function transformCodeForPreview(code: string) {
  if (!code) return { transformedCode: "", componentName: "App" };

  let transformed = code.trim();
  
  // 1. Remove markdown fences (e.g. ```jsx ... ```)
  if (transformed.includes("```")) {
    transformed = transformed.replace(/```[a-zA-Z]*\n?/g, "").replace(/```/g, "");
  }

  // 2. Strip import statements (basic regex)
  transformed = transformed.replace(/^import\s+.*?;\s*$/gm, '');
  transformed = transformed.replace(/^import\s+.*?\s+from\s+['"].*?['"];?\s*$/gm, '');

  // 3. Normalize component names to 'App'
  // Replace "export default function GeneratedApp" or "function GeneratedApp" with "App"
  // We look for common patterns generated by AI
  const namesToNormalize = ['GeneratedApp', 'Component', 'UI', 'Dashboard', 'LandingPage'];
  namesToNormalize.forEach(name => {
    const regex = new RegExp(`\\b${name}\\b`, 'g');
    transformed = transformed.replace(regex, 'App');
  });

  // 4. Handle exports
  let hasDefaultExport = false;
  
  // Find "export default function App"
  if (/export\s+default\s+function\s+App/.test(transformed)) {
    hasDefaultExport = true;
  } else if (/export\s+default\s+App/.test(transformed)) {
    hasDefaultExport = true;
  }

  // If no default export but function App exists, add it
  if (!hasDefaultExport && /\bfunction\s+App\b/.test(transformed)) {
    transformed += "\n\nexport default App;";
    hasDefaultExport = true;
  }

  // If even function App doesn't exist, try to rename whatever the main function is
  if (!hasDefaultExport) {
     const functionMatch = transformed.match(/function\s+([A-Z][a-zA-Z0-9_]*)\s*\(/);
     if (functionMatch) {
       const detectedName = functionMatch[1];
       transformed = transformed.replace(new RegExp(`\\b${detectedName}\\b`, 'g'), 'App');
       transformed += "\n\nexport default App;";
     }
  }

  // Strip all "export" keywords to avoid Babel module issues in some standalone configurations, 
  // but here we actually want them because we use type="text/babel" data-type="module"
  // Actually, Babel Standalone with data-type="module" handles "export default" correctly by 
  // turning the script into an ESM module.

  // Provide a fallback lucide icons mock if it tries to use them
  const iconMock = `
  const Icons = new Proxy({}, {
    get: function(target, prop) {
      return function(props) {
        return React.createElement('div', { ...props, className: (props.className || '') + ' w-5 h-5 bg-gray-200 rounded flex items-center justify-center text-[10px] overflow-hidden', title: prop }, prop.substring(0, 2));
      }
    }
  });
  window.LucideIcons = Icons;
  `;

  return { transformedCode: transformed, componentName: 'App', iconMock };
}
